// One-off generator: Natural Earth 110m land GeoJSON -> a single SVG path
// string, projected equirectangular over a fixed lon/lat window. The window
// is exported alongside so the React component can place city dots with the
// exact same projection (guaranteeing dots land on the right spot).
//
// Usage:  node scripts/gen-worldmap.mjs <path-to-ne_110m_land.json>
// Writes: data/worldmap.ts
//
// The source GeoJSON is NOT committed; regenerate only if you want to tweak
// the projection window or resolution. Land data: Natural Earth (public domain).

import { readFileSync, writeFileSync } from "node:fs";

const src = process.argv[2];
if (!src) {
  console.error("Usage: node scripts/gen-worldmap.mjs <ne_110m_land.json>");
  process.exit(1);
}

// Projection window. Full longitude; latitude cropped to drop Antarctica and
// the empty high Arctic. All collaborator cities fall inside this window
// (Glasgow ~55.9 N down to Montevideo ~34.9 S).
const LON_MIN = -180;
const LON_MAX = 180;
const LAT_MAX = 83.6;
const LAT_MIN = -56;

// Keep degrees-per-pixel equal on both axes so continents aren't stretched.
const W = 1000;
const H = Math.round(((LAT_MAX - LAT_MIN) / (LON_MAX - LON_MIN)) * W);

const projX = (lon) => ((lon - LON_MIN) / (LON_MAX - LON_MIN)) * W;
const projY = (lat) => ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * H;
const r1 = (n) => Math.round(n * 10) / 10;

const geo = JSON.parse(readFileSync(src, "utf8"));

function ringToPath(ring) {
  // Skip rings entirely south of the window (Antarctica).
  const maxLat = Math.max(...ring.map((p) => p[1]));
  if (maxLat < LAT_MIN) return "";
  let d = "";
  for (let i = 0; i < ring.length; i++) {
    const [lon, lat] = ring[i];
    const x = r1(projX(lon));
    const y = r1(projY(lat));
    d += (i === 0 ? "M" : "L") + x + " " + y + " ";
  }
  return d + "Z";
}

const paths = [];
for (const f of geo.features) {
  const g = f.geometry;
  if (!g) continue;
  if (g.type === "Polygon") {
    for (const ring of g.coordinates) paths.push(ringToPath(ring));
  } else if (g.type === "MultiPolygon") {
    for (const poly of g.coordinates)
      for (const ring of poly) paths.push(ringToPath(ring));
  }
}

const d = paths.filter(Boolean).join("");

const out = `// AUTO-GENERATED by scripts/gen-worldmap.mjs — do not edit by hand.
// Land silhouette (Natural Earth 110m, public domain) projected equirectangular.
// Use PROJECT() to place markers with the same projection the path was built with.

export const WORLD_VIEWBOX = { w: ${W}, h: ${H} } as const;

const LON_MIN = ${LON_MIN};
const LON_MAX = ${LON_MAX};
const LAT_MAX = ${LAT_MAX};
const LAT_MIN = ${LAT_MIN};

/** Project [lon, lat] (degrees) to viewBox coordinates. */
export function project(lon: number, lat: number): { x: number; y: number } {
  return {
    x: ((lon - LON_MIN) / (LON_MAX - LON_MIN)) * WORLD_VIEWBOX.w,
    y: ((LAT_MAX - lat) / (LAT_MAX - LAT_MIN)) * WORLD_VIEWBOX.h,
  };
}

export const WORLD_PATH =
  "${d}";
`;

writeFileSync(new URL("../data/worldmap.ts", import.meta.url), out);
console.error(`Wrote data/worldmap.ts  (viewBox ${W}x${H}, path ${d.length} chars)`);
